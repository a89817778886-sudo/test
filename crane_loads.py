def get_d2_for_crane(capacity: int, boom: int, height_to_arm: int) -> int | None:
    """Возвращает D2 (мм) для конфигурации крана ЛКС73.
    Возвращает None, если конфигурация не найдена в таблице.
    """
    try:
        return CRANE_D2.get((int(capacity), int(boom), int(height_to_arm)))
    except Exception:
        return None


def get_flange_code_for_d2(d2: int) -> str | None:
    """Возвращает код уширенного фланца по D2."""
    return FLANGE_D2_TO_CODE.get(d2)


def get_flange_code_for_crane(capacity: int, boom: int, height_to_arm: int) -> str | None:
    """Полный подбор: конфигурация крана → D2 → уширенный фланец."""
    d2 = get_d2_for_crane(capacity, boom, height_to_arm)
    if d2 is None:
        return None
    return get_flange_code_for_d2(d2)
